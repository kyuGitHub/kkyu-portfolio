// Builds the static pages from src/pages/*.mjs into the repo root.
// Usage: node scripts/build.mjs   (no dependencies; output HTML is committed, Vercel serves it as-is)
import { writeFileSync, mkdirSync, readdirSync, readFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { layout, SITE } from './lib.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const dir = join(root, 'src/pages');
let n = 0;
const urls = [];
for (const f of readdirSync(dir).filter(f => f.endsWith('.mjs')).sort()) {
  const mod = await import(pathToFileURL(join(dir, f)).href);
  for (const p of [].concat(mod.default)) {
    const out = join(root, p.path);
    mkdirSync(dirname(out), { recursive: true });
    writeFileSync(out, layout(p));
    n++;
    if (!p.noindex) urls.push(SITE + (p.path === 'index.html' ? '/' : '/' + p.path));
    console.log('built', p.path);
  }
}
// One stylesheet: design-system tokens + site layer (avoids the @import waterfall)
const css = ['colors', 'typography', 'spacing', 'web'].map(f => readFileSync(join(root, `assets/ds/${f}.css`), 'utf8'))
  .concat(readFileSync(join(root, 'assets/site.css'), 'utf8').replace(/^@import[^;]+;\n/gm, ''))
  .join('\n');
writeFileSync(join(root, 'assets/site.bundle.css'), '/* Generated by scripts/build.mjs from assets/ds/*.css + assets/site.css. Do not edit. */\n' + css);
writeFileSync(join(root, 'sitemap.xml'), `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n${urls.map(u => `  <url><loc>${u}</loc></url>`).join('\n')}\n</urlset>\n`);
console.log(n + ' pages, ' + urls.length + ' in sitemap');
